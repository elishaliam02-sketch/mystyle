/**
 * Packs the converted food classifier (assets/model/food, written by
 * scripts/fetch-food-model.sh on CI) into one TypeScript module the app
 * imports: the graph, the weights as base64 and the labels.
 *
 * Inlined rather than loaded as asset files because reading a binary asset
 * back in React Native needs a native file-system module the app does not
 * ship — and a plain module is delivered by an over-the-air update like any
 * other code, with no new install.
 */
import fs from "node:fs";
import path from "node:path";

const DIR = path.resolve("assets/model/food");
const OUT = path.resolve("src/ai/foodModelData.ts");

const model = JSON.parse(fs.readFileSync(path.join(DIR, "model.json"), "utf8"));
const shards = model.weightsManifest.flatMap((g) => g.paths);
const weights = Buffer.concat(shards.map((p) => fs.readFileSync(path.join(DIR, p))));

// labels.csv: "id,name" with a header row; the id is the model's output index.
const rows = fs.readFileSync(path.join(DIR, "labels.csv"), "utf8").trim().split(/\r?\n/).slice(1);
const labels = [];
for (const row of rows) {
  const comma = row.indexOf(",");
  const id = Number(row.slice(0, comma));
  labels[id] = row.slice(comma + 1).replace(/^"|"$/g, "").trim();
}

const { weightsManifest, ...rest } = model;
const json = { ...rest, weightsManifest: weightsManifest.map((g) => ({ weights: g.weights })) };

fs.writeFileSync(
  OUT,
  `// Generated by scripts/pack-food-model.mjs — do not edit by hand.
// Google AIY food_V1 classifier (Apache-2.0), TensorFlow.js, 8-bit weights.
/* eslint-disable */
export const MODEL_JSON = ${JSON.stringify(json)};
export const WEIGHTS_B64 = ${JSON.stringify(weights.toString("base64"))};
export const LABELS: string[] = ${JSON.stringify(labels)};
`,
);
console.log(`packed ${shards.length} shard(s), ${(weights.length / 1024 / 1024).toFixed(1)} MB, ${labels.filter(Boolean).length} labels`);
