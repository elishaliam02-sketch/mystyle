/**
 * Ships the exercise photographs inside the app.
 *
 * They used to load from jsDelivr's GitHub mirror of free-exercise-db while the
 * workout was on screen. That mirror refuses repositories over its size limit —
 * this one is — so on phones the photos never arrived and every move showed
 * only its drawn muscle map. Now each mapped photo is downloaded once, from
 * GitHub itself, shrunk to what a thumbnail needs, and saved in
 * assets/exercises/. The images are public domain (the Unlicense).
 *
 * Run: npm install --no-save sharp && node scripts/bundle-exercise-images.mjs
 * Writes assets/exercises/*.jpg and src/workout/exerciseImageAssets.ts.
 */
import { build } from "esbuild";
import { pathToFileURL } from "node:url";
import fs from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";

const sharp = createRequire(import.meta.url)("sharp");
const OUT = path.resolve("assets/exercises");
const MAP_FILE = path.resolve("src/workout/exerciseImageAssets.ts");
// Thumbnails are drawn at up to ~120 px; 320 px wide stays sharp on a dense
// screen and keeps the lot around two megabytes.
const WIDTH = 320;

const bundle = path.resolve("node_modules/.cache/exerciseimages.mjs");
await build({ entryPoints: ["src/workout/images.ts"], bundle: true, format: "esm", platform: "node", outfile: bundle, logLevel: "warning" });
const { EXERCISE_IMAGE } = await import(pathToFileURL(bundle).href);

/** jsDelivr's GitHub mirror → the same file straight from GitHub. */
const rawUrl = (u) =>
  u.replace("https://cdn.jsdelivr.net/gh/yuhonas/free-exercise-db@main/", "https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/");

await fs.rm(OUT, { recursive: true, force: true });
await fs.mkdir(OUT, { recursive: true });
const ids = Object.keys(EXERCISE_IMAGE).sort();
async function fetchShrunk(url) {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(url);
      if (res.ok) {
        const bytes = Buffer.from(await res.arrayBuffer());
        return await sharp(bytes).resize({ width: WIDTH, withoutEnlargement: true }).jpeg({ quality: 72, mozjpeg: true }).toBuffer();
      }
      if (res.status === 404) return null;
    } catch {}
  }
  return null;
}

const done = [];
const ends = [];
for (const id of ids) {
  // Frame 0 is the start position — the thumbnail. Frame 1, when the set has
  // one, is the end position: the two together show the movement itself.
  const start = await fetchShrunk(rawUrl(EXERCISE_IMAGE[id]));
  if (!start) {
    console.log(`FAIL  ${id}`);
    continue;
  }
  await fs.writeFile(path.join(OUT, `${id}.jpg`), start);
  done.push(id);
  const end = await fetchShrunk(rawUrl(EXERCISE_IMAGE[id]).replace(/\/0\.jpg$/, "/1.jpg"));
  if (end) {
    await fs.writeFile(path.join(OUT, `${id}-end.jpg`), end);
    ends.push(id);
  }
  console.log(`  ok  ${id}  ${(start.length / 1024).toFixed(0)} KB${end ? ` + end ${(end.length / 1024).toFixed(0)} KB` : ""}`);
}

await fs.writeFile(
  MAP_FILE,
  `// Generated by scripts/bundle-exercise-images.mjs — do not edit by hand.
// Public-domain exercise photographs (free-exercise-db), shipped inside the app
// so every move shows its photo at once, offline, with nothing requested.
import type { ImageSourcePropType } from "react-native";

export const BUNDLED_EXERCISE_IMAGES: Record<string, ImageSourcePropType> = {
${done.map((id) => `  ${JSON.stringify(id)}: require(${JSON.stringify(`../../assets/exercises/${id}.jpg`)}),`).join("\n")}
};

/** The end position of the movement, for moves whose set has one. */
export const BUNDLED_EXERCISE_END: Record<string, ImageSourcePropType> = {
${ends.map((id) => `  ${JSON.stringify(id)}: require(${JSON.stringify(`../../assets/exercises/${id}-end.jpg`)}),`).join("\n")}
};
`,
);
console.log(`\n${done.length}/${ids.length} bundled`);
if (done.length < ids.length) process.exitCode = 1;
