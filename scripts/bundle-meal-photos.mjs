/**
 * Ships a real photograph of every library dish inside the app.
 *
 * The app used to search Wikimedia Commons for each card while it was on
 * screen. That depends on the network, on the photos switch, and on Wikimedia
 * accepting the phone's request — and on a phone it refused them (see
 * PHOTO_USER_AGENT in src/kitchen/photo.ts), so people saw drawings where the
 * photos should have been. The photos are chosen the same way — the app's own
 * `photoQueries` ladder and `pickPhoto` filter — but once, here, and saved into
 * assets/meals/ with the credit their licence asks for.
 *
 * Every dish gets a different photo: a picture already taken by an earlier
 * dish is passed over for the next good one.
 *
 * Needs the open internet, so it runs on CI (`.github/workflows/meal-photos.yml`),
 * which commits assets/meals/ and src/kitchen/mealPhotoAssets.ts back.
 */
import { build } from "esbuild";
import { pathToFileURL } from "node:url";
import fs from "node:fs/promises";
import path from "node:path";

const ASSET_DIR = path.resolve("assets/meals");
const MAP_FILE = path.resolve("src/kitchen/mealPhotoAssets.ts");
// Wikimedia serves thumbnails in fixed width steps; 500 is the one that stays
// sharp on a phone-width card without making the app heavy.
const WIDTH = 500;
const UA = "APEX-app/1.0 (https://github.com/elishaliam02-sketch/mystyle)";

const bundle = path.resolve("node_modules/.cache/photobundle.mjs");
await build({
  entryPoints: ["src/kitchen/index.ts"],
  bundle: true, format: "esm", platform: "node", outfile: bundle,
  alias: { "@": path.resolve("src") }, logLevel: "warning",
});
const { MEALS, commonsSearchUrl, photoQueries, pickPhoto } = await import(pathToFileURL(bundle).href);

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function get(url) {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(url, { headers: { "User-Agent": UA } });
      if (res.ok) return res;
      if (res.status !== 429 && res.status < 500) return null;
    } catch {}
    await sleep(1500 * (attempt + 1));
  }
  return null;
}

const used = new Set();
const entries = [];
await fs.rm(ASSET_DIR, { recursive: true, force: true });
await fs.mkdir(ASSET_DIR, { recursive: true });

for (const meal of MEALS) {
  let chosen = null;
  for (const query of photoQueries(meal)) {
    const res = await get(commonsSearchUrl(query, WIDTH));
    const body = res ? await res.json().catch(() => null) : null;
    const photo = pickPhoto(body?.query?.pages ?? [], used);
    if (photo) {
      chosen = photo;
      break;
    }
  }
  if (!chosen) {
    console.log(`MISS  ${meal.id}`);
    continue;
  }
  const img = await get(chosen.url);
  const bytes = img ? Buffer.from(await img.arrayBuffer()) : null;
  // A JPEG starts FF D8; anything else is an error page, not a photo.
  if (!bytes || bytes.length < 2000 || bytes[0] !== 0xff || bytes[1] !== 0xd8) {
    console.log(`FAIL  ${meal.id} — could not download ${chosen.url}`);
    continue;
  }
  used.add(chosen.url);
  await fs.writeFile(path.join(ASSET_DIR, `${meal.id}.jpg`), bytes);
  entries.push({ id: meal.id, credit: chosen.credit });
  console.log(`  ok  ${meal.id}  ${(bytes.length / 1024).toFixed(0)} KB`);
  await sleep(150); // polite against a free public API
}

const lines = entries
  .sort((a, b) => a.id.localeCompare(b.id))
  .map(
    (e) =>
      `  ${JSON.stringify(e.id)}: { source: require(${JSON.stringify(`../../assets/meals/${e.id}.jpg`)}), credit: ${JSON.stringify(e.credit)} },`,
  );
await fs.writeFile(
  MAP_FILE,
  `// Generated by scripts/bundle-meal-photos.mjs — do not edit by hand.
// Real photographs of each library dish, from Wikimedia Commons, shipped inside
// the app so a card shows its dish at once, offline, with nothing requested.
import type { ImageSourcePropType } from "react-native";

export type BundledPhoto = { source: ImageSourcePropType; credit: string | null };

export const BUNDLED_MEAL_PHOTOS: Record<string, BundledPhoto> = {
${lines.join("\n")}
};
`,
);
console.log(`\n${entries.length}/${MEALS.length} dishes bundled`);
if (entries.length < MEALS.length * 0.8) {
  console.error("Too many dishes without a photo — refusing to replace the bundle.");
  process.exit(1);
}
