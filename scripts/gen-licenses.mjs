/**
 * Writes src/legal/licenses.ts from what is actually installed.
 *
 * Open-source licences have to be reproduced, and a hand-kept list goes stale
 * the first time someone runs `npm install`. So the list is generated: every
 * package the app depends on, directly or transitively, with its licence and
 * its author. Generated into source rather than read at runtime, because the
 * screen must work offline and node_modules does not ship in a bundle.
 *
 *   node scripts/gen-licenses.mjs
 *
 * Run it after adding or upgrading a dependency; the file is committed.
 */
import { readFile, writeFile, readdir } from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const MODULES = path.join(ROOT, "node_modules");

async function readJson(file) {
  try {
    return JSON.parse(await readFile(file, "utf8"));
  } catch {
    return null;
  }
}

/** Every installed package directory, including scoped ones. */
async function packageDirs() {
  const out = [];
  const entries = await readdir(MODULES, { withFileTypes: true });
  for (const entry of entries) {
    if (!entry.isDirectory() || entry.name === ".cache" || entry.name === ".bin") continue;
    if (entry.name.startsWith("@")) {
      const scoped = await readdir(path.join(MODULES, entry.name), { withFileTypes: true });
      for (const inner of scoped) {
        if (inner.isDirectory()) out.push(path.join(MODULES, entry.name, inner.name));
      }
    } else {
      out.push(path.join(MODULES, entry.name));
    }
  }
  return out;
}

const licenseOf = (pkg) => {
  if (typeof pkg.license === "string") return pkg.license;
  if (pkg.license?.type) return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type ?? l).join(" / ");
  return "";
};

const authorOf = (pkg) => {
  if (typeof pkg.author === "string") return pkg.author.replace(/\s*<[^>]*>/g, "").replace(/\s*\([^)]*\)/g, "").trim();
  if (pkg.author?.name) return pkg.author.name;
  return "";
};

const rows = [];
for (const dir of await packageDirs()) {
  const pkg = await readJson(path.join(dir, "package.json"));
  if (!pkg?.name || !pkg.version) continue;
  const license = licenseOf(pkg);
  if (!license) continue;
  rows.push({ name: pkg.name, version: pkg.version, license, author: authorOf(pkg) });
}
rows.sort((a, b) => a.name.localeCompare(b.name));

const body = rows
  .map((r) => `  { name: ${JSON.stringify(r.name)}, version: ${JSON.stringify(r.version)}, license: ${JSON.stringify(r.license)}, author: ${JSON.stringify(r.author)} },`)
  .join("\n");

const file = `/**
 * The open-source packages this app is built on, and their licences.
 *
 * GENERATED by scripts/gen-licenses.mjs — do not edit by hand. Regenerate it
 * after adding or upgrading a dependency:
 *
 *     node scripts/gen-licenses.mjs
 *
 * It is committed rather than read at runtime: the licence screen has to work
 * offline, and node_modules is not part of the bundle.
 */

export type PackageLicense = {
  name: string;
  version: string;
  license: string;
  author: string;
};

export const LICENSES: PackageLicense[] = [
${body}
];

/** How many licences are being reproduced — for the screen's subtitle. */
export const LICENSE_COUNT = LICENSES.length;
`;

await writeFile(path.join(ROOT, "src/legal/licenses.ts"), file);
console.log(`wrote src/legal/licenses.ts — ${rows.length} packages`);
